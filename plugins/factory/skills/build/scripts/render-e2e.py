#!/usr/bin/env python3
"""Render a validated factory.e2e/1 sidecar into the e2e HTML report.

    render-e2e.py <plan>-e2e.json --out <plan>-e2e-report.html

The sidecar is the record; the HTML is presentation. The record is validated
strictly (no expressions, no duplicate keys, bounded size), every screenshot file
is checked against its sha256, and the data is embedded as inert JSON between the
template's E2E_DATA markers. Screenshot paths are rewritten relative to the output.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "scripts"))
import factory_records as records  # noqa: E402

TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "e2e-report.html"
START, END = "/* E2E_DATA_START", "/* E2E_DATA_END */"


def fail(message: str) -> int:
    print(f"render-e2e: {message}", file=sys.stderr)
    return 1


def render(sidecar: Path, out: Path) -> dict:
    record = records.load_e2e(sidecar)
    problems = records.verify_e2e_evidence(record, sidecar.parent)
    if problems:
        raise records.RecordError("record.evidence", "; ".join(problems[:10]))
    view = json.loads(json.dumps(record))
    for scenario in view["scenarios"]:
        for shot in scenario.get("screenshots", []):
            target = (sidecar.parent / shot["file"]).resolve()
            shot["src"] = Path(os.path.relpath(target, out.parent.resolve())).as_posix()
    view["summary"] = records.e2e_counts(record)
    payload = json.dumps(view, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    template = TEMPLATE.read_text(encoding="utf-8")
    start = template.index(START)
    end = template.index(END) + len(END)
    block = f"{START} - generated by render-e2e.py from {sidecar.name}; edit the sidecar, not this block */\n" \
            f"const E2E_DATA = {payload};\n{END}"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(template[:start] + block + template[end:], encoding="utf-8")
    return view["summary"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sidecar")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    try:
        summary = render(Path(args.sidecar), Path(args.out))
    except records.RecordError as error:
        return fail(f"{error} [{error.code}]")
    print(json.dumps({"out": args.out, **summary}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
